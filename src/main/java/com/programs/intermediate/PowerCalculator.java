package com.programs.intermediate;

import java.util.Scanner;

/**
 * Power (Exponentiation) Calculator
 *
 * Concept:
 * Exponentiation is a mathematical operation involving two numbers: the base
 * and the exponent. It represents multiplying the base by itself the number
 * of times indicated by the exponent.
 *
 * Algorithm & Logic:
 * Instead of relying on Java's built-in Math.pow() method, this program
 * manually computes the result using an iterative loop.
 *
 * Edge Cases Handled:
 * - Negative Exponents: Mathematically, a negative exponent represents division
 *   (the reciprocal of the base raised to the positive exponent). The program
 *   calculates the positive power first, then inverses the result (1 / result).
 * - Zero Exponent: Any non-zero number raised to the power of 0 is 1. The
 *   program handles this naturally as the loop condition (i <= 0) instantly
 *   fails, leaving the default result as 1.
 * - Fractional Results: The return type is set to 'double' to safely accommodate
 *   the decimal outputs generated by negative exponents.
 *
 * Example 1 (Positive Exponent):
 * Input: Base = 2, Exponent = 3
 * Output: Final result: 8.0  (2 * 2 * 2)
 *
 * Example 2 (Negative Exponent):
 * Input: Base = 2, Exponent = -3
 * Output: Final result: 0.125  (1 / (2 * 2 * 2))
 */

public class PowerCalculator {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        System.out.println("~~~ Power Calculator ~~~");
        System.out.print("Enter the base value: ");
        int base = sc.nextInt();
        System.out.print("Enter the exponent value: ");
        int exponent = sc.nextInt();
        double finalResult = calculatePower(base, exponent);
        System.out.println("Final result: " + finalResult);
        sc.close();
    }

    public static double calculatePower(int base, int exponent){
        double result = 1;

        int positiveExponent = Math.abs(exponent);

        for(int i = 1; i <= positiveExponent; i++){
            result = result * base;
        }

        if(exponent < 0){
            result = 1 / result;
        }

        return result;
    }
}
