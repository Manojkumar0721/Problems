package com.programs.intermediate;

import java.util.Scanner;

/**
 * Permutations (nPr) and Combinations (nCr) Calculator
 *
 * Concept:
 * In combinatorics, these formulas calculate the number of ways to select 'r' items
 * from a total pool of 'n' items.
 * - Permutations (nPr) are used when the ORDER of the items matters (e.g., race placements, passwords).
 * - Combinations (nCr) are used when the ORDER does NOT matter (e.g., drawing a hand of cards, forming a team).
 *
 * Formulas:
 * nPr = n! / (n - r)!
 * nCr = n! / (r! * (n - r)!)
 *
 * Edge Cases Handled:
 * - Invalid Pool/Selection Size: Validates that 'n' and 'r' are strictly non-negative.
 * - Impossible Selections: Throws an IllegalArgumentException if 'r > n'. You mathematically
 *   cannot select more items than are available in the total pool.
 * - Factorial Scaling: Uses 'long' variables to handle the massive numbers generated by
 *   factorials, preventing early integer memory overflow.
 *
 * Example 1 (Permutation - Order Matters):
 * Input: n = 5, r = 3, Option = 1
 * Output: 60
 * (Ways to award 1st, 2nd, and 3rd place to 5 racers)
 *
 * Example 2 (Combination - Order Doesn't Matter):
 * Input: n = 5, r = 3, Option = 2
 * Output: 10
 * (Ways to select a team of 3 members from 5 people)
 */

public class PermutationCombination {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        System.out.println("~~~ Permutations (nPr) and Combinations (nCr) ~~~");
        System.out.print("Enter the Total number of items (n): ");
        int n = sc.nextInt();
        System.out.print("Enter the number of items being chosen (r): ");
        int r = sc.nextInt();
        System.out.println("-Choose option (1) for permutation.");
        System.out.println("-Choose option (2) for combination.");
        int op = sc.nextInt();
        switch (op) {
            case 1:
                long nPrResult = nPr(n, r);
                System.out.println("nPr: " + nPrResult);
                break;
            case 2:
                long nCrResult = nCr(n, r);
                System.out.println("nCr: " + nCrResult);
                break;
            default:
                System.out.println("Invalid option!");
        }
        sc.close();
    }

    public static long nPr(int n, int r){
        if(n < 0 || r < 0 || r > n){
            throw new IllegalArgumentException("Invalid input!, n and r can't be negative and cannot be grater than n");
        }
        return calculateFactorial(n) / calculateFactorial((n-r));
    }

    public static long nCr(int n, int r){
        if(n < 0 || r < 0 || r > n){
            throw new IllegalArgumentException("Invalid input!, n and r can't be negative and cannot be grater than n");
        }
        return calculateFactorial(n)/ ((long) calculateFactorial(r) * calculateFactorial(n-r));
    }


    public static long calculateFactorial(int number){
        long result = 1;
        for(int i=1;i<=number;i++){
            result = result * i;
        }
        return result;
    }

}
